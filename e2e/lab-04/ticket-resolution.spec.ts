import { test, expect, login, openTicket, saveAction, capture } from "./fixtures";
test("Requester advisory preserves OPEN; Staff records final work then resolves and closes via valid transitions", async ({ data, roles }, info) => {
 const ticket = await data.ticket("Resolution journey", "OPEN", data.staff.id);
 await login(roles.requester, data.requester, data.password); await openTicket(roles.requester, ticket.id);
 await roles.requester.getByRole("button", { name: /Problem Appears Resolved/i }).click();
 const confirmation = roles.requester.getByRole("dialog");
 await confirmation.getByTestId("resolve-comment-input").fill("Synthetic requester confirms service appears restored");
 await confirmation.getByRole("button", { name: "Confirm Resolution", exact: true }).click(); await expect(confirmation).toBeHidden();
 await expect(roles.requester.getByTestId("header-ticket-status")).toHaveText("OPEN");
 await roles.requester.reload(); await expect(roles.requester.getByTestId("header-ticket-status")).toHaveText("OPEN");
 const advisory = await data.p.ticket.findUniqueOrThrow({ where: { id: ticket.id } });
 expect(advisory.status).toBe("OPEN"); expect(advisory.problemAppearsResolved).toBe(true);
 await expect(roles.requester.getByTestId("detail-status-select")).toHaveCount(0);
 await capture(roles.requester, info, "requester-advisory-open", data.prefix);
 await login(roles.staff, data.staff, data.password); await openTicket(roles.staff, ticket.id);
 await expect(roles.staff.getByText("Synthetic requester confirms service appears restored", { exact: true })).toBeVisible();
 await saveAction(roles.staff, `${data.prefix} final verification`);
 await roles.staff.getByLabel("Status Transition").selectOption("RESOLVED");
 await expect(roles.staff.getByTestId("header-ticket-status")).toHaveText("RESOLVED");
 await roles.staff.reload(); await expect(roles.staff.getByTestId("header-ticket-status")).toHaveText("RESOLVED");
 expect((await data.p.ticket.findUniqueOrThrow({ where: { id: ticket.id } })).status).toBe("RESOLVED");
 await capture(roles.staff, info, "staff-formally-resolved", data.prefix);
 await roles.staff.getByLabel("Status Transition").selectOption("CLOSED");
 await expect(roles.staff.getByTestId("header-ticket-status")).toHaveText("CLOSED");
 await roles.staff.reload(); await expect(roles.staff.getByTestId("header-ticket-status")).toHaveText("CLOSED");
 await roles.requester.reload(); await expect(roles.requester.getByTestId("header-ticket-status")).toHaveText("CLOSED");
 expect((await data.p.ticket.findUniqueOrThrow({ where: { id: ticket.id } })).status).toBe("CLOSED");
 await capture(roles.requester, info, "requester-final-closed", data.prefix);
});
